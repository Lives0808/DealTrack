/**
 * Release signing.
 *
 * The keystore is generated locally and never committed (see .gitignore).
 * If `keystore.properties` is absent, the release build falls back to the debug
 * signing config so `assembleRelease` still produces an installable APK — which
 * is what CI and the GitHub release need.
 */
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}
val hasReleaseKeystore = keystoreProps.getProperty("storeFile") != null

