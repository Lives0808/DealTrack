/**
 * Proforma invoice (形式发票).
 *
 * Deliberately built on the same renderer and layout language as the quotation —
 * a buyer should recognise it as "the same document, one step later", not as a
 * different company's paperwork. What changes is the content: PI number instead
 * of quote number, a payment schedule with due dates, and the bank details a
 * buyer needs in order to actually pay.
 */

