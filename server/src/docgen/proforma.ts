function localized(table: Record<string, Record<string, string>>, key: string, language: string, fallback: string): string {
  const entry = table[key];
  if (!entry) return fallback;
  return entry[language.split('-')[0]!] ?? entry.en ?? fallback;
}

export function buildPiHtml(quoteId: string): { html: string; baseName: string; language: string } | null {
  const pi = getPiByQuote(quoteId);
  if (!pi) return null;
  return buildPiHtmlFrom(pi);
}

export function buildPiHtmlFrom(pi: ProformaInvoice): { html: string; baseName: string; language: string } | null {
  const quote = pi.quote;
  if (!quote) return null;

  const customer = getCustomer(pi.customerId);
  const company = getCompany();
  const sales = getSalesIdentity();
  const language = pi.language || 'en';
  const labels = piLabels(language);
  const rtl = isRtl(language);
  const money = (value: number) => formatNumber(value, language, 2);
  const date = (value: string | null | undefined) => (value ? formatDate(value, language) : '—');

  const rows = (quote.items ?? [])
    .map(
      (item) => `
      <tr>
        <td class="num">${item.lineNo}</td>
        <td>
          <div>${escapeHtml(item.description)}</div>
          ${item.sku ? `<div class="sku">SKU ${escapeHtml(item.sku)}${item.hsCode ? ` · HS ${escapeHtml(item.hsCode)}` : ''}</div>` : ''}
        </td>
        <td class="num">${formatNumber(item.qty, language, 0)}</td>
        <td>${escapeHtml(item.unit)}</td>
        <td class="num">${money(item.unitPrice)}</td>
        <td class="num">${money(item.amount)}</td>
      </tr>`,
    )
    .join('');

  const milestones = (pi.milestones ?? [])
    .map(
      (milestone) => `
      <tr>
        <td>${escapeHtml(milestoneLabel(milestone.label, language))}</td>
        <td>${date(milestone.dueAt)}</td>
        <td class="num">${escapeHtml(milestone.currency)} ${money(milestone.amount)}</td>
        <td><span class="badge ${milestone.status === 'paid' ? 'ok' : milestone.status === 'overdue' ? 'bad' : 'warn'}">${escapeHtml(
          localized(MILESTONE_STATUS, milestone.status, language, milestone.status),
        )}</span></td>
      </tr>`,
    )
    .join('');

  const html = `<!doctype html>
<html lang="${escapeHtml(language)}" dir="${rtl ? 'rtl' : 'ltr'}">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(pi.piNo)} · ${escapeHtml(customer?.company ?? '')}</title>
<style>${documentStyles('#1c6b4a')}</style>
</head>
<body class="${rtl ? 'rtl' : ''}">
<div class="doc">
  <header class="doc-header">
    <div>
      <div class="seller-name">${escapeHtml(company.name)}</div>
      ${company.nameZh ? `<div class="seller-meta">${escapeHtml(company.nameZh)}</div>` : ''}
      <div class="seller-meta">${escapeHtml([company.address, `${company.city}, ${company.country}`].filter(Boolean).join('\n'))}</div>
      <div class="seller-meta"><bdi>${escapeHtml([company.email, company.phone].filter(Boolean).join(' · '))}</bdi></div>
    </div>
    <div class="doc-title">
      <div class="label">${labels.title}</div>
      <div class="no">${escapeHtml(pi.piNo)}</div>
      <div class="date">${labels.date}: ${date(pi.issuedAt)}</div>
      <div class="date">${labels.quoteRef}: ${escapeHtml(quote.quoteNo)}</div>
      <div class="date">${labels.validUntil}: ${date(pi.validUntil)}</div>
    </div>
  </header>

  <section class="parties">
    <div class="party">
      <h3>${labels.buyer}</h3>
      <div class="name">${escapeHtml(customer?.company ?? '—')}</div>
      ${customer?.contactName ? `<div class="line">${labels.attn}: ${escapeHtml(customer.contactName)}</div>` : ''}
      ${customer?.email ? `<div class="line"><bdi>${escapeHtml(customer.email)}</bdi></div>` : ''}
      ${customer?.country ? `<div class="line">${escapeHtml(customer.country)}</div>` : ''}
    </div>
    <div class="party">
      <h3>${labels.seller}</h3>
      <div class="name">${escapeHtml(company.name)}</div>
      <div class="line">${escapeHtml(company.address)}</div>
      <div class="line">${escapeHtml(`${company.city}, ${company.country}`)}</div>
    </div>
  </section>

  <table class="items">
    <thead>
      <tr>
        <th style="width:7%">${labels.item}</th>
        <th>${labels.description}</th>
        <th style="width:11%" class="num">${labels.qty}</th>
        <th style="width:9%">${labels.unit}</th>
        <th style="width:15%" class="num">${labels.unitPrice}</th>
        <th style="width:16%" class="num">${labels.amount}</th>
      </tr>
    </thead>
    <tbody>${rows || `<tr><td colspan="6">—</td></tr>`}</tbody>
  </table>

  <div class="totals">
    <table>
      <tr><td class="label">${labels.subtotal}</td><td class="value">${escapeHtml(pi.currency)} ${money(pi.subtotal)}</td></tr>
      ${pi.freight > 0 ? `<tr><td class="label">${labels.freight}</td><td class="value">${escapeHtml(pi.currency)} ${money(pi.freight)}</td></tr>` : ''}
      ${pi.insurance > 0 ? `<tr><td class="label">${labels.insurance}</td><td class="value">${escapeHtml(pi.currency)} ${money(pi.insurance)}</td></tr>` : ''}
      <tr class="grand"><td class="label">${labels.total}</td><td class="value">${escapeHtml(pi.currency)} ${money(pi.total)}</td></tr>
    </table>
  </div>

  <h3 style="margin-top:20px; font-size:11pt">${labels.paymentSchedule}</h3>
  <table class="checklist">
    <thead>
      <tr>
        <th style="width:22%">${labels.milestone}</th>
        <th style="width:22%">${labels.dueDate}</th>
        <th style="width:24%" class="num">${labels.amountDue}</th>
        <th>${labels.status}</th>
      </tr>
    </thead>
    <tbody>${milestones || `<tr><td colspan="4">—</td></tr>`}</tbody>
  </table>

  <section class="terms" style="margin-top:16px">
    <h3>${labels.bankDetails}</h3>
    <dl>
      <dd style="grid-column:1 / -1"><bdi>${escapeHtml(pi.bankInfo || company.bankInfo)}</bdi></dd>
    </dl>
  </section>

  <section class="terms">
    <h3>${labels.terms}</h3>
    <dl>
      <dt>${labels.incoterm}</dt><dd><bdi>${escapeHtml(pi.incoterm)} ${escapeHtml(pi.incotermPlace)}</bdi></dd>
      <dt>${labels.paymentSchedule}</dt><dd><bdi>${escapeHtml(pi.paymentTerms ?? quote.paymentTerms ?? '')}</bdi></dd>
      <dt>${labels.shipment}</dt><dd>${date(pi.shipmentDate)}</dd>
    </dl>
  </section>

  ${pi.notes ? `<div class="notes">${labels.notes}: <bdi>${escapeHtml(pi.notes)}</bdi></div>` : ''}

  <section class="signature">
    <div class="block">
      <div>${labels.signature}</div>
      <div style="margin-top:16px">${escapeHtml(sales.senderName)} · ${escapeHtml(sales.senderRole)}</div>
    </div>
    <div class="stamp">${labels.stamp}</div>
  </section>

  <footer class="doc-footer">
    ${escapeHtml(labels.declaration)}<br/>
    ${labels.generated} · ${escapeHtml(pi.piNo)} · ${escapeHtml(quote.quoteNo)}
  </footer>
</div>
</body>
</html>`;

  return { html, baseName: pi.piNo, language };
}

export async function generatePiPdf(quoteId: string): Promise<string | null> {
  const built = buildPiHtml(quoteId);
  if (!built) return null;
  const rendered: RenderedDocument = await renderDocument({
    html: built.html,
    baseName: built.baseName,
    subdir: 'proforma',
  });
  return rendered.pdfPath ?? rendered.htmlPath;
}

